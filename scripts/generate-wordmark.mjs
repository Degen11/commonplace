// Generates an SVG path for the "Commonplace" wordmark, traced from Playfair
// Display Bold, and writes it to src/components/wordmarkPath.js.
//
// Run with: npm run wordmark
//
// Why: the wordmark used to be a <span> styled with Playfair Display,
// pulled in via a render-blocking Google Fonts stylesheet for those 11
// characters. Tracing the letterforms once at build-prep time removes that
// whole font (and its preconnect + stylesheet) from the page — the
// <Wordmark> component just draws a path.
//
// Depends on Google Fonts still serving Playfair Display Bold at this
// versioned URL (the "v40" static asset, requested as raw TTF via the
// legacy v1 CSS API so no woff2 decompression is needed in Node). If Google
// Fonts revs the font and this URL 404s, update it from a fresh
// `curl -H 'User-Agent: Mozilla/5.0 (Linux; U; Android 2.2)' \
//   'https://fonts.googleapis.com/css?family=Playfair+Display:700'`.
import opentype from 'opentype.js';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../src/components');
const FONT_URL = 'https://fonts.gstatic.com/s/playfairdisplay/v40/nuFvD-vYSZviVYUb_rj3ij__anPXJzDwcbmjWBN2PKeiunDXbtY.ttf';
const TEXT = 'Commonplace';

const res = await fetch(FONT_URL);
if (!res.ok) throw new Error(`Font fetch failed (${res.status}) — see comment at top of this script`);
const buf = await res.arrayBuffer();
const font = opentype.parse(buf);

// opentype.js's getPath(text, x, y, fontSize) already returns coordinates in
// SVG/canvas convention (y increases downward, `y` is the baseline row) — no
// manual axis flip needed, just normalize the tight bounding box down to a
// viewBox starting at (0,0) so the component can size it with a single
// `height` prop, same as an icon.
const fontSize = font.unitsPerEm;
const path = font.getPath(TEXT, 0, 0, fontSize);
const box = path.getBoundingBox();

const scale = 1 / fontSize;
const height = (box.y2 - box.y1) * scale;
const width = (box.x2 - box.x1) * scale;
const translateX = -box.x1 * scale;
const translateY = -box.y1 * scale;

const scaledPath = new opentype.Path();
for (const cmd of path.commands) {
  const c = { ...cmd };
  for (const [xKey, yKey] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
    if (c[xKey] !== undefined) c[xKey] = c[xKey] * scale + translateX;
    if (c[yKey] !== undefined) c[yKey] = c[yKey] * scale + translateY;
  }
  scaledPath.commands.push(c);
}
const d = scaledPath.toPathData(4);

const out = `// Generated by scripts/generate-wordmark.mjs — do not hand-edit.
// Traced from Playfair Display Bold so the "Commonplace" wordmark no longer
// needs that font loaded in the browser. Re-run \`npm run wordmark\` if the
// wordmark text or source font ever changes.
export const WORDMARK_PATH = "${d}";
export const WORDMARK_VIEWBOX = "0 0 ${width.toFixed(4)} ${height.toFixed(4)}";
export const WORDMARK_ASPECT_RATIO = ${(width / height).toFixed(6)};
`;

writeFileSync(resolve(outDir, 'wordmarkPath.js'), out);
console.log(`  wordmarkPath.js (viewBox 0 0 ${width.toFixed(2)} ${height.toFixed(2)})`);
